def clean_tweet(text):
    text = html.unescape(str(text))
    text = re.sub(r"https?://\\S+|www\\.\\S+", " URL ", text)
    text = re.sub(r"@\\w+", " USER ", text)
    return re.sub(r"\\s+", " ", text).strip()


def build_model():
    return Pipeline([
        ("tfidf", TfidfVectorizer(
            lowercase=True,
            ngram_range=(1, 2),
            max_features=50000,
            sublinear_tf=True,
            min_df=2,
        )),
        ("classifier", LogisticRegression(
            max_iter=1500,
            class_weight="balanced",
            random_state=42,
        )),
    ])


@st.cache_resource
def load_or_train_model():
    if MODEL_PATH.is_file():
        try:
            return joblib.load(MODEL_PATH)
        except Exception:
            pass

    if not DATASET_PATH.is_file():
        raise FileNotFoundError(
            "twitter_data.csv was not found. Upload it beside app.py."
        )

    data = pd.read_csv(DATASET_PATH)
    if not {"tweet", "class"}.issubset(data.columns):
        raise ValueError("Dataset must contain 'tweet' and 'class' columns.")

    data = data[["tweet", "class"]].dropna()
    data["class"] = pd.to_numeric(data["class"], errors="coerce")
    data = data.dropna(subset=["class"])
    data["class"] = data["class"].astype(int)
    data = data[data["class"].isin([0, 1, 2])]
    data["tweet"] = data["tweet"].apply(clean_tweet)
    data = data[data["tweet"].str.len() > 0]

    if data.empty or data["class"].nunique() < 2:
        raise ValueError("Dataset needs examples from at least two classes.")

    model = build_model()
    model.fit(data["tweet"], data["class"])
    try:
        joblib.dump(model, MODEL_PATH)
    except Exception:
        pass
    return model


def predict_text(model, text):
    cleaned = clean_tweet(text)
    if not cleaned:
        raise ValueError("Please enter some text to analyse.")
    prediction = int(model.predict([cleaned])[0])
    probabilities = model.predict_proba([cleaned])[0]
    classes = model.named_steps["classifier"].classes_
    scores = {int(label): float(score) for label, score in zip(classes, probabilities)}
    return prediction, scores


